export function getTranslation(lang: Language, key: keyof typeof i18n['en']): string {
  const dictionary = i18n[lang] || i18n['en'];
  return (dictionary[key] as string) || (i18n['en'][key] as string) || String(key);
}
export function translate(lang: Language) {
  return (key: keyof typeof i18n['en']) => getTranslation(lang, key);
}
